/**
 * URL helpers and the list of pages that exist.
 *
 * EN lives at /, FR mirrors the same slugs under /fr/.
 * `isBuilt()` knows every page in the build (static files in src/pages plus
 * content pages), so links to pages that do not exist yet render as plain
 * text instead of breaking.
 */
import { getCollection, type CollectionEntry } from 'astro:content';
import type { Locale } from '../data/business';
import { reviews } from '../data/reviews';
import { partners } from '../data/partners';

export type ContentCollection = 'services' | 'villages' | 'guides' | 'pages';

/** '/services/chalets/' + 'fr' -> '/fr/services/chalets/' */
export function localize(path: string, locale: Locale): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return locale === 'en' ? clean : `/fr${clean}`;
}

/** '/fr/services/' -> '/services/' */
export function unlocalize(path: string): string {
  return path.replace(/^\/fr(\/|$)/, '/');
}

/** Unlocalized URL path of a content entry. */
export function contentPath(collection: ContentCollection, slug: string): string {
  switch (collection) {
    case 'services': return `/services/${slug}/`;
    case 'guides': return `/guides/${slug}/`;
    case 'villages': return `/${slug}/`;
    case 'pages': return `/${slug}/`;
  }
}

/** Entry id is '<locale>/<slug>'. */
export function splitId(id: string): { locale: Locale; slug: string } {
  const [locale, ...rest] = id.split('/');
  return { locale: locale as Locale, slug: rest.join('/') };
}

export interface ContentPage {
  collection: ContentCollection;
  locale: Locale;
  slug: string;
  /** Unlocalized path, the same for EN and FR. */
  path: string;
  entry: CollectionEntry<ContentCollection>;
}

let cache: Promise<ContentPage[]> | undefined;

export function getContentPages(): Promise<ContentPage[]> {
  cache ??= (async () => {
    const out: ContentPage[] = [];
    for (const collection of ['services', 'villages', 'guides', 'pages'] as const) {
      for (const entry of await getCollection(collection)) {
        const { locale, slug } = splitId(entry.id);
        out.push({ collection, locale, slug, path: contentPath(collection, slug), entry });
      }
    }
    return out;
  })();
  return cache;
}

/** Pages generated by src/pages/[...slug].astro only when they have real data. */
export const conditionalPages = {
  '/reviews/': reviews.length > 0,
  '/partners/': partners.length > 0,
} as const;

const staticRoutes = Object.keys(import.meta.glob('/src/pages/**/*.{astro,md,mdx}'))
  .filter((f) => !f.includes('['))
  .map((f) =>
    f
      .replace('/src/pages', '')
      .replace(/\.(astro|mdx?)$/, '')
      .replace(/\/index$/, '/')
      .replace(/([^/])$/, '$1/'),
  );

let built: Promise<Set<string>> | undefined;

function builtRoutes(): Promise<Set<string>> {
  built ??= (async () => {
    const set = new Set(staticRoutes);
    for (const p of await getContentPages()) set.add(localize(p.path, p.locale));
    for (const [path, on] of Object.entries(conditionalPages)) {
      if (on) for (const l of ['en', 'fr'] as const) set.add(localize(path, l));
    }
    return set;
  })();
  return built;
}

export async function isBuilt(path: string): Promise<boolean> {
  return (await builtRoutes()).has(path.split('#')[0] || '/');
}

/** Title to show when linking to a path (falls back to undefined). */
export async function linkTitle(path: string, locale: Locale): Promise<string | undefined> {
  const page = (await getContentPages()).find((p) => p.path === path && p.locale === locale);
  return page ? (page.entry.data.shortTitle ?? page.entry.data.title) : undefined;
}
